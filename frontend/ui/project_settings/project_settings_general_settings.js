/**
 * Project Settings - General Settings (origin / development boundary months)
 *
 * Owns the canonical year-month parsing used across Project Settings, the
 * per-project General Settings cache, its `/general_settings` reads and
 * writes, and the dates shown on the Source Data period band. The band only
 * displays them; the Project Dates panel is the one place they change.
 */

const MONTH_ABBR = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"];

const MONTH_TOKENS = {
  jan: 1, january: 1,
  feb: 2, february: 2,
  mar: 3, march: 3,
  apr: 4, april: 4,
  may: 5,
  jun: 6, june: 6,
  jul: 7, july: 7,
  aug: 8, august: 8,
  sep: 9, sept: 9, september: 9,
  oct: 10, october: 10,
  nov: 11, november: 11,
  dec: 12, december: 12,
};

export const EMPTY_GENERAL_SETTINGS = Object.freeze({
  projectName: "",
  projectFolderName: "",
  projectNameMismatch: false,
  autoGenerated: true,
  originStartDate: "",
  originEndDate: "",
  developmentEndDate: "",
});

function normalizeBoundaryIntegerText(value) {
  const raw = String(value ?? "").trim();
  if (!raw) return "";
  const compact = raw.replace(/,/g, "");
  const m = compact.match(/^(-?\d+)(?:\.0+)?$/);
  if (!m) return raw;
  const intPart = String(m[1] || "");
  const sign = intPart.startsWith("-") ? "-" : "";
  const digits = sign ? intPart.slice(1) : intPart;
  const normalizedDigits = digits.replace(/^0+(?=\d)/, "");
  return sign + normalizedDigits;
}

function normalizeYmParts(yearRaw, monthRaw) {
  const year = Number(yearRaw);
  const month = Number(monthRaw);
  if (!Number.isInteger(year) || year < 1) return "";
  if (!Number.isInteger(month) || month < 1 || month > 12) return "";
  return String(year).padStart(4, "0") + String(month).padStart(2, "0");
}

function monthTokenToNumber(token) {
  const key = String(token || "").trim().toLowerCase();
  if (!key) return null;
  return Object.prototype.hasOwnProperty.call(MONTH_TOKENS, key) ? MONTH_TOKENS[key] : null;
}

/** Parse any supported boundary spelling into canonical `YYYYMM`. */
export function normalizeBoundaryYmCanonical(value) {
  const raw = String(value ?? "").trim();
  if (!raw) return "";

  const compact = normalizeBoundaryIntegerText(raw);
  let m = compact.match(/^(\d{4})(\d{2})$/);
  if (m) return normalizeYmParts(m[1], m[2]);

  m = raw.match(/^(\d{4})\s*[-/]\s*(\d{1,2})$/);
  if (m) return normalizeYmParts(m[1], m[2]);

  m = raw.match(/^(\d{1,2})\s*[-/]\s*(\d{4})$/);
  if (m) return normalizeYmParts(m[2], m[1]);

  m = raw.match(/^([A-Za-z]{3,9})[\s,/-]+(\d{4})$/);
  if (m) {
    const month = monthTokenToNumber(m[1]);
    if (month != null) return normalizeYmParts(m[2], month);
  }

  m = raw.match(/^(\d{4})[\s,/-]+([A-Za-z]{3,9})$/);
  if (m) {
    const month = monthTokenToNumber(m[2]);
    if (month != null) return normalizeYmParts(m[1], month);
  }

  return "";
}

export function formatBoundaryYmDisplay(value) {
  const canonical = normalizeBoundaryYmCanonical(value);
  if (!canonical) return "";
  const year = canonical.slice(0, 4);
  const month = Number(canonical.slice(4, 6));
  if (!Number.isInteger(month) || month < 1 || month > 12) return "";
  return `${MONTH_ABBR[month - 1]} ${year}`;
}

function normalizeGeneralSettingsBool(value, fallback = false) {
  if (typeof value === "boolean") return value;
  if (typeof value === "number") return value !== 0;
  const s = String(value ?? "").trim().toLowerCase();
  if (s === "1" || s === "true" || s === "yes" || s === "y" || s === "on") return true;
  if (s === "0" || s === "false" || s === "no" || s === "n" || s === "off") return false;
  return !!fallback;
}

/**
 * @param {object} deps
 * @param {Function} deps.setStatus
 * @param {Function} deps.normalizeProjectKey
 * @param {Function} deps.readResponseErrorDetail
 * @param {Function} deps.getSelectedProject
 * @param {Function} deps.onDatesShown  Called after the band's dates are rewritten.
 * @param {Function} deps.fetchImpl
 * @param {object} deps.displays  `{ originStartDate: element, ... }`, display only
 */
export function createGeneralSettingsFeature(deps) {
  const {
    setStatus,
    normalizeProjectKey,
    readResponseErrorDetail,
    getSelectedProject,
    onDatesShown,
    fetchImpl,
    displays = {},
  } = deps;

  const generalSettingsByProject = new Map();

  function normalizeValues(values = {}) {
    const projectName = String(values?.projectName ?? values?.project_name ?? "").trim();
    const projectFolderName = String(values?.projectFolderName ?? values?.project_folder_name ?? "").trim();
    const inferredMismatch = (
      projectName
      && projectFolderName
      && normalizeProjectKey(projectName) !== normalizeProjectKey(projectFolderName)
    );
    return {
      projectName,
      projectFolderName,
      projectNameMismatch: normalizeGeneralSettingsBool(values?.projectNameMismatch ?? values?.project_name_mismatch, inferredMismatch),
      autoGenerated: normalizeGeneralSettingsBool(values?.autoGenerated ?? values?.auto_generated, false),
      originStartDate: normalizeBoundaryYmCanonical(values?.originStartDate ?? values?.origin_start_date ?? ""),
      originEndDate: normalizeBoundaryYmCanonical(values?.originEndDate ?? values?.origin_end_date ?? ""),
      developmentEndDate: normalizeBoundaryYmCanonical(values?.developmentEndDate ?? values?.development_end_date ?? ""),
    };
  }

  function getCache(projectName) {
    const key = normalizeProjectKey(projectName);
    if (!key) return normalizeValues(EMPTY_GENERAL_SETTINGS);
    return normalizeValues(generalSettingsByProject.get(key) || EMPTY_GENERAL_SETTINGS);
  }

  function setCache(projectName, values = {}) {
    const key = normalizeProjectKey(projectName);
    if (!key) return normalizeValues(EMPTY_GENERAL_SETTINGS);
    const normalized = normalizeValues(values);
    generalSettingsByProject.set(key, normalized);
    return normalized;
  }

  function hasValues(values = {}) {
    const v = normalizeValues(values);
    return !!(v.originStartDate || v.originEndDate || v.developmentEndDate);
  }

  function areEqual(a = {}, b = {}) {
    const left = normalizeValues(a);
    const right = normalizeValues(b);
    return (
      left.autoGenerated === right.autoGenerated
      && left.originStartDate === right.originStartDate
      && left.originEndDate === right.originEndDate
      && left.developmentEndDate === right.developmentEndDate
    );
  }

  /** Show the three period dates on the band from canonical or free-form values. */
  function showDates(values = {}) {
    const shown = {
      originStartDate: values?.originStart,
      originEndDate: values?.originEnd,
      developmentEndDate: values?.developmentEnd,
    };
    for (const [key, value] of Object.entries(shown)) {
      if (displays[key]) displays[key].textContent = formatBoundaryYmDisplay(value || "");
    }
    onDatesShown?.();
  }

  /** Apply a cached/loaded settings record to the band. */
  function applyValuesToInputs(values) {
    showDates({
      originStart: values.originStartDate,
      originEnd: values.originEndDate,
      developmentEnd: values.developmentEndDate,
    });
  }

  function isStillSelected(name) {
    const selected = getSelectedProject();
    return !!selected && selected.name === name;
  }

  async function load(projectName, options = {}) {
    const applyToInputs = !!options?.applyToInputs;
    const name = String(projectName || "").trim();
    const empty = normalizeValues(EMPTY_GENERAL_SETTINGS);
    if (!name) return empty;

    try {
      const res = await fetchImpl(`/general_settings?project_name=${encodeURIComponent(name)}`);
      if (!res.ok) throw new Error(await readResponseErrorDetail(res));
      const out = await res.json();
      const values = setCache(name, normalizeValues(out?.data || {}));
      if (applyToInputs && isStillSelected(name)) applyValuesToInputs(values);
      return values;
    } catch (err) {
      setStatus(`Failed to load General Settings: ${err.message}`);
      const values = setCache(name, empty);
      if (applyToInputs && isStillSelected(name)) applyValuesToInputs(values);
      return values;
    }
  }

  async function ensureLoaded(projectName, options = {}) {
    const applyToInputs = !!options?.applyToInputs;
    const name = String(projectName || "").trim();
    if (!name) return normalizeValues(EMPTY_GENERAL_SETTINGS);
    const key = normalizeProjectKey(name);
    if (generalSettingsByProject.has(key)) {
      const values = getCache(name);
      if (applyToInputs && isStillSelected(name)) applyValuesToInputs(values);
      return values;
    }
    return load(name, { applyToInputs });
  }

  /**
   * Write the dates read off a new project's source table, or re-save them
   * under a renamed project. A person changes them only through the Project
   * Dates panel's job.
   */
  async function save(projectName, values = {}, options = {}) {
    const force = !!options?.force;
    const autoGenerated = normalizeGeneralSettingsBool(options?.autoGenerated, false);
    const name = String(projectName || "").trim();
    if (!name) return { ok: false, data: normalizeValues(EMPTY_GENERAL_SETTINGS) };

    const normalized = normalizeValues({ ...values, autoGenerated });
    const cached = getCache(name);
    if (!force && areEqual(cached, normalized)) {
      return { ok: true, skipped: true, data: cached };
    }

    try {
      const res = await fetchImpl("/general_settings", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          project_name: name,
          origin_start_date: normalized.originStartDate,
          origin_end_date: normalized.originEndDate,
          development_end_date: normalized.developmentEndDate,
          auto_generated: normalized.autoGenerated,
        }),
      });
      if (!res.ok) throw new Error(await readResponseErrorDetail(res));
      const out = await res.json();
      const saved = setCache(name, normalizeValues(out?.data || normalized));
      return { ok: true, data: saved };
    } catch (err) {
      setStatus(`Failed to save General Settings: ${err.message}`);
      return { ok: false, data: normalized };
    }
  }

  /** Drop every cached record, e.g. when the project map is reloaded. */
  function clearCache() {
    generalSettingsByProject.clear();
  }

  return {
    clearCache,
    ensureLoaded,
    getCache,
    hasValues,
    load,
    save,
    showDates,
  };
}
